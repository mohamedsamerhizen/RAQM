using System.IO.Compression;
using System.Text;
using System.Xml;
using RAQM.Api.DTOs.FinancialReporting;
using RAQM.Api.Helpers;

namespace RAQM.Api.Helpers.FinancialReporting;

public static class FinancialExportWriter
{
    private static IEnumerable<(string Key, string Value)> Metadata(FinancialReport report)
    {
        yield return ("Report", report.Kind.ToString());
        yield return ("Company", $"{report.CompanyName} ({report.CompanyId})");
        yield return ("Currency", report.Currency);
        yield return ("Definition revision", report.DefinitionRevision.ToString(System.Globalization.CultureInfo.InvariantCulture));
        yield return ("Generated by", report.Actor.ToString());
        yield return ("Generated at (UTC)", FormattableString.Invariant($"{report.GeneratedAt:O}"));
        yield return ("Period", FormattableString.Invariant($"{report.Period.From:yyyy-MM-dd} to {report.Period.To:yyyy-MM-dd}"));
        if (report.Comparison is { } prior)
            yield return ("Comparative period", FormattableString.Invariant($"{prior.From:yyyy-MM-dd} to {prior.To:yyyy-MM-dd}"));
        yield return ("Posted sequence cutoff", report.PostedSequenceCutoff.ToString(System.Globalization.CultureInfo.InvariantCulture));
        yield return ("Integrity difference", Number(report.IntegrityDifference));
        if (report.ComparativeIntegrityDifference is { } comparative)
            yield return ("Comparative integrity difference", Number(comparative));
        foreach (var warning in report.Warnings) yield return ("Warning", warning);
    }

    public static byte[] Csv(FinancialReport report)
    {
        var text = new StringBuilder();
        foreach (var (key, value) in Metadata(report)) text.Append(Field(key)).Append(',').Append(Field(value)).Append("\r\n");
        text.Append("\r\nKey,Label,Amount,Comparative,ChangePercent,AccountId\r\n");
        foreach (var row in report.Rows)
            text.Append(Field(row.Key)).Append(',').Append(Field(row.Label)).Append(',').Append(Number(row.Amount)).Append(',')
                .Append(Number(row.Comparative)).Append(',').Append(Number(row.ChangePercent)).Append(',').Append(row.AccountId).Append("\r\n");
        return Encoding.UTF8.GetPreamble().Concat(Encoding.UTF8.GetBytes(text.ToString())).ToArray();
    }

    public static byte[] Pdf(FinancialReport report)
    {
        var lines = Metadata(report).Select(x => $"{x.Key}: {x.Value}").Append("")
            .Concat(report.Rows.Select(row => $"{row.Label}: {Number(row.Amount)}" +
                (row.Comparative is { } prior ? $" | prior {Number(prior)}" : "") +
                (row.ChangePercent is { } change ? $" | {Number(change)}%" : "")))
            .ToArray();
        if (lines.Any(line => line.Any(c => c is < ' ' or > '~')))
            throw new ApiException(422, "PDF supports printable ASCII only. Use CSV or XLSX for this report.", "report_pdf_text");
        lines = lines.SelectMany(Wrap).ToArray();
        var pages = lines.Chunk(48).ToArray();
        var objects = new List<string>
        {
            "<< /Type /Catalog /Pages 2 0 R >>",
            $"<< /Type /Pages /Count {pages.Length} /Kids [{string.Join(' ', pages.Select((_, i) => $"{4 + i * 2} 0 R"))}] >>",
            "<< /Type /Font /Subtype /Type1 /BaseFont /Courier /Encoding /WinAnsiEncoding >>"
        };
        for (var i = 0; i < pages.Length; i++)
        {
            var stream = "BT /F1 10 Tf 13 TL 43 790 Td\n" +
                string.Join('\n', pages[i].Select(line => $"({Literal(line)}) Tj T*")) + "\nET\n";
            objects.Add($"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 3 0 R >> >> /Contents {5 + i * 2} 0 R >>");
            objects.Add($"<< /Length {Encoding.ASCII.GetByteCount(stream)} >>\nstream\n{stream}endstream");
        }
        var pdf = new StringBuilder("%PDF-1.4\n");
        var offsets = new List<int>();
        for (var i = 0; i < objects.Count; i++)
        {
            offsets.Add(pdf.Length);
            pdf.Append(i + 1).Append(" 0 obj\n").Append(objects[i]).Append("\nendobj\n");
        }
        var xref = pdf.Length;
        pdf.Append("xref\n0 ").Append(objects.Count + 1).Append("\n0000000000 65535 f \n");
        foreach (var offset in offsets) pdf.Append(FormattableString.Invariant($"{offset:D10} 00000 n \n"));
        pdf.Append(FormattableString.Invariant($"trailer\n<< /Size {objects.Count + 1} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n"));
        return Encoding.ASCII.GetBytes(pdf.ToString());
    }

    public static byte[] Xlsx(FinancialReport report)
    {
        const string sheetNamespace = "http://schemas.openxmlformats.org/spreadsheetml/2006/main";
        using var output = new MemoryStream();
        using (var zip = new ZipArchive(output, ZipArchiveMode.Create, leaveOpen: true))
        {
            WritePart("[Content_Types].xml", """
                <Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
                  <Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>
                  <Default Extension="xml" ContentType="application/xml"/>
                  <Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/>
                  <Override PartName="/xl/worksheets/sheet1.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>
                </Types>
                """);
            WritePart("_rels/.rels", """
                <Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
                  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/>
                </Relationships>
                """);
            WritePart("xl/workbook.xml", """
                <workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"
                          xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">
                  <sheets><sheet name="Financial report" sheetId="1" r:id="rId1"/></sheets>
                </workbook>
                """);
            WritePart("xl/_rels/workbook.xml.rels", """
                <Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
                  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet1.xml"/>
                </Relationships>
                """);
            using var sheet = zip.CreateEntry("xl/worksheets/sheet1.xml").Open();
            using var writer = XmlWriter.Create(sheet, new XmlWriterSettings { Encoding = new UTF8Encoding(false) });
            writer.WriteStartElement("worksheet", sheetNamespace);
            writer.WriteStartElement("sheetData", sheetNamespace);
            foreach (var (key, value) in Metadata(report)) WriteRow(key, value);
            WriteRow("Key", "Label", "Amount", "Comparative", "ChangePercent", "AccountId");
            foreach (var row in report.Rows) WriteRow(row.Key, row.Label, row.Amount, row.Comparative, row.ChangePercent, row.AccountId?.ToString());
            writer.WriteEndElement();
            writer.WriteEndElement();

            void WritePart(string path, string xml)
            {
                using var stream = new StreamWriter(zip.CreateEntry(path).Open(), new UTF8Encoding(false));
                stream.Write(xml);
            }
            void WriteRow(params object?[] values)
            {
                writer.WriteStartElement("row", sheetNamespace);
                foreach (var value in values)
                {
                    writer.WriteStartElement("c", sheetNamespace);
                    var number = value is decimal amount ? Number(amount) : null;
                    if (number is not null && number.Count(char.IsAsciiDigit) <= 15)
                        writer.WriteElementString("v", sheetNamespace, number);
                    else if ((number ?? value as string) is { } text)
                    {
                        writer.WriteAttributeString("t", "inlineStr");
                        writer.WriteStartElement("is", sheetNamespace);
                        writer.WriteStartElement("t", sheetNamespace);
                        writer.WriteAttributeString("xml", "space", "http://www.w3.org/XML/1998/namespace", "preserve");
                        writer.WriteString(string.Concat(text.Where(XmlConvert.IsXmlChar)));
                        writer.WriteEndElement();
                        writer.WriteEndElement();
                    }
                    writer.WriteEndElement();
                }
                writer.WriteEndElement();
            }
        }
        return output.ToArray();
    }

    private static string Number(decimal? amount) => amount?.ToString("0.####", System.Globalization.CultureInfo.InvariantCulture) ?? "";
    private static string Field(string value)
    {
        var first = value.TrimStart();
        if (first.Length > 0 && first[0] is '=' or '+' or '-' or '@') value = "'" + value;
        return "\"" + value.Replace("\"", "\"\"", StringComparison.Ordinal) + "\"";
    }
    private static IEnumerable<string> Wrap(string line)
    {
        if (line.Length == 0) yield return "";
        for (var offset = 0; offset < line.Length; offset += 80) yield return line.Substring(offset, Math.Min(80, line.Length - offset));
    }
    private static string Literal(string text) => string.Concat(text.Select(c => c switch
    {
        '(' or ')' or '\\' => "\\" + c,
        >= ' ' and <= '~' => c.ToString(),
        _ => "?"
    }));
}
